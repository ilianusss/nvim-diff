local H = require("tests.helpers")
local git = require("nvim-diff.git")

local function by_path(list)
    local out = {}
    for _, e in ipairs(list) do
        out[e.path] = e
    end
    return out
end

test("status lists modified, untracked, deleted, staged and renamed files", function()
    local repo =
        H.repo({ ["mod.txt"] = "a\nb\n", ["del.txt"] = "x\n", ["old.txt"] = "one\ntwo\nthree\n", ["both.txt"] = "1\n" })
    repo:write("mod.txt", "a\nB\nc\n")
    os.remove(repo.root .. "/del.txt")
    repo:write("dir/new.txt", "new\n")
    repo:git("mv", "old.txt", "renamed.txt")
    repo:write("both.txt", "2\n")
    repo:git("add", "both.txt")
    repo:write("both.txt", "3\n")

    local st = assert(git.status(repo.root))
    local working, staged = by_path(st.working), by_path(st.staged)
    eq(working["mod.txt"].status, "M")
    eq(working["mod.txt"].stats, { additions = 2, deletions = 1 })
    eq(working["del.txt"].status, "D")
    eq(working["dir/new.txt"].status, "?")
    eq(working["both.txt"].status, "M")
    eq(staged["both.txt"].status, "M")
    eq(staged["renamed.txt"].status, "R")
    eq(staged["renamed.txt"].old_path, "old.txt")
    eq(staged["renamed.txt"].stats, { additions = 0, deletions = 0 })
    eq(#st.conflicting, 0)
end)

test("paths with spaces and unicode survive -z parsing", function()
    local repo = H.repo({ ["a b/c d.txt"] = "1\n" })
    repo:write("a b/c d.txt", "2\n")
    repo:write("é è.txt", "x\n")
    local working = by_path(assert(git.status(repo.root)).working)
    ok(working["a b/c d.txt"], "spaces")
    ok(working["é è.txt"], "unicode")
end)

test("async status calls back on the main loop", function()
    local repo = H.repo({ ["a.txt"] = "1\n" })
    repo:write("a.txt", "2\n")
    local got
    git.status(repo.root, function(st)
        got = st
    end)
    H.wait(function()
        return got ~= nil
    end)
    eq(got.working[1].path, "a.txt")
end)

test("binary files are flagged", function()
    local repo = H.repo({ ["bin.dat"] = "\0\1\2" })
    repo:write("bin.dat", "\0\3\4")
    eq(assert(git.status(repo.root)).working[1].binary, true)
end)

test("conflicts are listed with their marker count", function()
    local repo = H.repo({ ["keep.txt"] = "k\n" })
    repo:conflict("c.txt")
    local st = assert(git.status(repo.root))
    eq(#st.conflicting, 1)
    eq(st.conflicting[1].path, "c.txt")
    eq(st.conflicting[1].status, "U")
    eq(st.conflicting[1].xy, "UU")
    eq(st.conflicting[1].conflicts, 1)
end)

