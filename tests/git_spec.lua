test("split_lines drops a uniform CR like a dos buffer", function()
    eq(git.split_lines("a\r\nb\r\n"), { "a", "b" })
    eq(git.split_lines("a\r\nb\n"), { "a\r", "b" })
    eq(git.split_lines(""), {})
    eq(git.split_lines("no newline"), { "no newline" })
end)

test("stage, unstage, stage all, unstage all", function()
    local repo = H.repo({ ["a.txt"] = "1\n", ["b.txt"] = "1\n" })
    repo:write("a.txt", "2\n")
    repo:write("b.txt", "2\n")
    repo:write("c.txt", "new\n")

    ok(git.stage(repo.root, { "a.txt" }))
    local st = assert(git.status(repo.root))
    eq(#st.staged, 1)
    eq(st.staged[1].path, "a.txt")

    ok(git.unstage(repo.root, { "a.txt" }))
    eq(#assert(git.status(repo.root)).staged, 0)

    ok(git.stage_all(repo.root))
    st = assert(git.status(repo.root))
    eq(#st.staged, 3)
    eq(#st.working, 0)

    ok(git.unstage_all(repo.root))
    st = assert(git.status(repo.root))
    eq(#st.staged, 0)
    eq(#st.working, 3)
end)

test("unstage works before the first commit", function()
    local repo = H.repo()
    repo:write("a.txt", "1\n")
    ok(git.stage(repo.root, { "a.txt" }))
    eq(assert(git.status(repo.root)).staged[1].status, "A")
    ok(git.unstage(repo.root, { "a.txt" }))
    eq(assert(git.status(repo.root)).working[1].status, "?")
    ok(git.stage_all(repo.root))
    ok(git.unstage_all(repo.root))
    eq(#assert(git.status(repo.root)).staged, 0)
end)

test("unstaging a rename unstages both sides", function()
    local repo = H.repo({ ["old.txt"] = "one\ntwo\nthree\n" })
    repo:git("mv", "old.txt", "new.txt")
    local e = assert(git.status(repo.root)).staged[1]
    ok(git.unstage(repo.root, { e.path, e.old_path }))
    local st = assert(git.status(repo.root))
    eq(#st.staged, 0)
    local working = by_path(st.working)
    eq(working["old.txt"].status, "D")
    eq(working["new.txt"].status, "?")
end)

test("restore: working change, untracked file, staged change", function()
    local repo = H.repo({ ["a.txt"] = "1\n", ["b.txt"] = "1\n" })
    repo:write("a.txt", "2\n")
    repo:write("u.txt", "u\n")
    repo:write("b.txt", "2\n")
    repo:git("add", "b.txt")
    repo:write("b.txt", "3\n")

    local working = by_path(assert(git.status(repo.root)).working)
    local hash = git.backup(repo.root, { "a.txt" })["a.txt"]
    ok(git.restore(repo.root, { working["a.txt"] }))
    eq(repo:read("a.txt"), "1\n")
    eq(repo:git("cat-file", "-p", hash), "2\n", "backup keeps the discarded content")

    ok(git.restore(repo.root, { working["u.txt"] }))
    eq(repo:exists("u.txt"), false)

    local staged = by_path(assert(git.status(repo.root)).staged)
    ok(git.restore(repo.root, { staged["b.txt"] }))
    eq(repo:read("b.txt"), "1\n")
    local st = assert(git.status(repo.root))
    eq(#st.staged + #st.working, 0)
end)

test("restore of a staged new file removes it (with and without HEAD)", function()
    local repo = H.repo({ ["a.txt"] = "1\n" })
    repo:write("n.txt", "n\n")
    repo:git("add", "n.txt")
    ok(git.restore(repo.root, assert(git.status(repo.root)).staged))
    eq(repo:exists("n.txt"), false)

    local fresh = H.repo()
    fresh:write("n.txt", "n\n")
    fresh:git("add", "n.txt")
    ok(git.restore(fresh.root, assert(git.status(fresh.root)).staged))
    eq(fresh:exists("n.txt"), false)
end)

test("repo() finds the root from a subfolder", function()
    local repo = H.repo({ ["sub/dir/a.txt"] = "1\n" })
    local r = assert(git.repo(repo.root .. "/sub/dir"))
    eq(r.root, repo.root)
    ok(r.gitdir:find("%.git$"))
    eq(git.repo(vim.fn.tempname()), nil)
end)

test("restore discards several working entries at once: modified, untracked, deleted", function()
    local repo = H.repo({ ["a.txt"] = "1\n", ["d.txt"] = "d\n" })
    repo:write("a.txt", "2\n")
    repo:write("u.txt", "u\n")
    os.remove(repo.root .. "/d.txt")

    ok(git.restore(repo.root, assert(git.status(repo.root)).working))
    eq(repo:read("a.txt"), "1\n")
    eq(repo:exists("u.txt"), false)
    eq(repo:read("d.txt"), "d\n")
    eq(#assert(git.status(repo.root)).working, 0)
end)

test("restore discards several staged entries at once, both sides of a rename included", function()
    local repo = H.repo({ ["a.txt"] = "1\n", ["old.txt"] = "one\ntwo\nthree\n" })
    repo:write("a.txt", "2\n")
    repo:write("n.txt", "n\n")
    repo:git("add", "a.txt", "n.txt")
    repo:git("mv", "old.txt", "new.txt")

    ok(git.restore(repo.root, assert(git.status(repo.root)).staged))
    eq(repo:read("a.txt"), "1\n")
    eq(repo:exists("n.txt"), false)
    eq(repo:read("old.txt"), "one\ntwo\nthree\n")
    eq(repo:exists("new.txt"), false)
    local st = assert(git.status(repo.root))
    eq(#st.staged + #st.working, 0)
end)

test("backup writes one blob per existing path and skips missing ones", function()
    local repo = H.repo()
    repo:write("a.txt", "a\n")
    repo:write("b.txt", "b\n")
    local hashes = git.backup(repo.root, { "a.txt", "gone.txt", "b.txt" })
    eq(vim.tbl_count(hashes), 2)
    eq(repo:git("cat-file", "-p", hashes["a.txt"]), "a\n")
    eq(repo:git("cat-file", "-p", hashes["b.txt"]), "b\n")
end)

test("backup skips directories (an untracked nested repo) and hashes the files next to them", function()
    local repo = H.repo({ ["a.txt"] = "1\n" })
    repo:write("a.txt", "2\n")
    local inner = H.repo({ ["x.txt"] = "x\n" })
    vim.uv.fs_rename(inner.root, repo.root .. "/inner")
    local hashes = assert(git.backup(repo.root, { "a.txt", "inner/" }))
    eq(vim.tbl_keys(hashes), { "a.txt" })
    eq(repo:git("cat-file", "-p", hashes["a.txt"]), "2\n")
end)

